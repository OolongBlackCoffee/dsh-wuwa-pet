# Install / remove the dsh-wuwa-pet logon autostart entry.
#
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools\autostart.ps1 install
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools\autostart.ps1 remove
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools\autostart.ps1 status
#
# The entry is a tiny .vbs in the user Startup folder, so no console window flashes
# at logon (a .cmd/.ps1 shortcut would). It only launches
# tools\autostart-launch.ps1 hidden, which does the real work.
#
# Keep this file ASCII-only: Windows PowerShell 5.1 reads BOM-less files as ANSI.
param(
  [ValidateSet('install', 'remove', 'status')]
  [string]$Action = 'status'
)

$ErrorActionPreference = 'Stop'

$Root = Split-Path -Parent $PSScriptRoot
$Launcher = Join-Path $PSScriptRoot 'autostart-launch.ps1'
$StartupDir = [Environment]::GetFolderPath('Startup')
$Entry = Join-Path $StartupDir 'dsh-wuwa-pet.vbs'

function Show-Status {
  $exists = Test-Path $Entry
  Write-Host ("startup folder : " + $StartupDir)
  Write-Host ("entry          : " + $Entry)
  Write-Host ("installed      : " + $exists)
  $bat = Test-Path (Join-Path $Root 'logs\autostart.log')
  Write-Host ("log            : " + (Join-Path $Root 'logs\autostart.log') + $(if ($bat) { '' } else { ' (not created yet)' }))
}

if ($Action -eq 'status') {
  Show-Status
  exit 0
}

if ($Action -eq 'remove') {
  if (Test-Path $Entry) {
    Remove-Item $Entry -Force
    Write-Host 'autostart removed' -ForegroundColor Yellow
  } else {
    Write-Host 'autostart not installed (nothing to do)'
  }
  Show-Status
  exit 0
}

if (-not (Test-Path $Launcher)) {
  Write-Host ("launcher missing: " + $Launcher) -ForegroundColor Red
  exit 1
}
if (-not (Test-Path $StartupDir)) {
  New-Item -ItemType Directory -Path $StartupDir -Force | Out-Null
}

# Build the .vbs: run powershell hidden (0 = no window, False = do not wait)
$psPath = Join-Path $env:SystemRoot 'System32\WindowsPowerShell\v1.0\powershell.exe'
$cmdline = '"' + $psPath + '" -NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File "' + $Launcher + '"'
$vbs = @()
$vbs += "' dsh-wuwa-pet autostart entry -- generated by tools\autostart.ps1"
$vbs += "' Delete this file (or run autostart.ps1 remove) to stop starting DSH + pet at logon."
$vbs += 'CreateObject("WScript.Shell").Run "' + ($cmdline -replace '"', '""') + '", 0, False'
Set-Content -Path $Entry -Value $vbs -Encoding ASCII

Write-Host 'autostart installed' -ForegroundColor Green
Show-Status
